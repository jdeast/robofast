"""A simulated telescope and camera on the sky, plugged in over Alpaca.

::

    python -m robofast.testing.sky_device [--catalog synthetic|gaia|...]
        [--site LAT,LON] [--pointing-error IH=150,ID=-40] [--discovery-port 32227]

serves, on loopback, a mount (:class:`~robofast.testing.pointing_sim.SkyMount`)
and a camera whose frames are the sky where the mount points
(:class:`~robofast.testing.focus_sim.StarfieldCamera` on a
:class:`~robofast.testing.skysim.SkyFocusScene`), as a telescope plugged
into a computer would appear: it answers Alpaca discovery and the
management API (:class:`~robofast.testing.alpaca_server.FakeAlpacaServer`),
and reports the ``FocalLength`` and ``PixelSizeX``/``PixelSizeY`` that give
its sky's plate scale, so :mod:`robofast.discover` reads them. The mount
points with ``--pointing-error`` (TPOINT terms, arcsec), which a pointing
run measures. It prints one JSON line (its address and discovery port) and
serves until stopped; it is a registered robofast simulator, so the
hardware gate accepts it.

The sky's stars come from a catalog source (:data:`robofast.catalog.CATALOG_SOURCES`):
``gaia`` (the real sky, downloaded) or ``synthetic``, which this module
registers: seeded random stars over the whole sky
(:class:`~robofast.testing.pointing_sim.SyntheticCatalog`) cut into the
catalog's HEALPix tiles, so a robofast config that names it
(``{"source": "synthetic"}``, with this module in ``plugins``) solves
against the same stars this camera shows, offline. It is a test source:
no data in it describe the real sky.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import signal
import threading
from datetime import UTC, datetime
from typing import Any

import numpy as np

from robofast import pointing as pm
from robofast.catalog import (
    CATALOG_SOURCES,
    TILE_DTYPE,
    CatalogSource,
    ang2pix,
    catalog_from_config,
    pix2ang,
)
from robofast.discover import ARCSEC_PER_UM_PER_MM
from robofast.testing.alpaca_server import FakeAlpacaServer
from robofast.testing.focus_sim import SimFocuser, StarfieldCamera
from robofast.testing.pointing_sim import SkyMount, SyntheticCatalog
from robofast.testing.skysim import SkyCamera, SkyFocusScene, SkyScene
from robofast.testing.starfield import Detector

#: The synthetic sky's stars (one seed: every process sees the same sky).
_SYNTHETIC = SyntheticCatalog(seed=7)


def _synthetic_tiles(url: str | None):
    def fetch(level: int, pix: int, mag_limit: float) -> np.ndarray:
        ra, dec = pix2ang(level, pix)
        radius = 1.2 * math.degrees(math.sqrt(4 * math.pi / (12 * 4**level)))
        stars = _SYNTHETIC.cone(float(ra[0]), float(dec[0]), radius)
        keep = (ang2pix(level, stars.ra, stars.dec) == pix) & (stars.g <= mag_limit)
        out = np.zeros(int(keep.sum()), dtype=TILE_DTYPE)
        out["source_id"] = stars.source_id[keep]
        out["ra"], out["dec"] = stars.ra[keep], stars.dec[keep]
        out["g"], out["bp_rp"] = stars.g[keep], 0.8
        return out

    return fetch


def register() -> None:
    """Register the ``synthetic`` catalog source (a robofast plug-in entry)."""
    if "synthetic" in CATALOG_SOURCES:
        return
    CATALOG_SOURCES.register(
        "synthetic",
        CatalogSource(
            name="synthetic",
            title="robofast's synthetic test sky (seeded random stars; not the real sky)",
            licence="generated by robofast's test kit (BSD 3-Clause)",
            noncommercial=False,
            licence_url="https://github.com/jdeast/robofast/blob/master/LICENSE",
            epoch=2016.0,
            proper_motion=False,
            directory="synthetic-g{mag:g}-hpx{level}",
            bright_file="synthetic_bright_stars.npy",
            magnitudes="G drawn from dN/dm ~ 10**(0.3 m)",
            fetcher=_synthetic_tiles,
        ),
    )


register()


def now() -> datetime:
    return datetime.now(UTC)


class SkyDevice:
    """The plugged-in telescope (module doc). ``catalog``: a ``catalog``
    config entry (:func:`robofast.catalog.catalog_from_config`)."""

    def __init__(
        self,
        *,
        catalog: dict[str, Any] | None = None,
        latitude: float = 42.38,
        longitude: float = -71.13,
        pointing_error: dict[str, float] | None = None,
        plate_scale: float = 1.5,
        pixel_size: float = 9.0,
        shape: tuple[int, int] = (768, 768),
        host: str = "127.0.0.1",
        port: int = 0,
        discovery_port: int | None = 0,
    ) -> None:
        self.mount = SkyMount(now, latitude, longitude, slew_time=0.5)
        #: What the mount reports (m): the focal length that, with the
        #: camera's pixels, gives the sky's plate scale.
        self.mount.FocalLength = ARCSEC_PER_UM_PER_MM * pixel_size / plate_scale / 1000.0
        camera = SkyCamera(
            shape=shape, plate_scale=plate_scale, pixel_size=pixel_size, detector=Detector(shape)
        )
        self.sky = SkyScene(
            catalog_from_config({"source": "synthetic", **(catalog or {})}),
            camera=camera,
            site=(latitude, longitude),
            pointing=pm.PointingModel(dict(pointing_error or {}), mount="equatorial"),
            sky_mag=21.0,
            seeing=2.5,
        )
        scene = SkyFocusScene(self.sky, self.mount, now, effective_exposure=10.0)
        self.focuser = SimFocuser(position=20000)
        self.camera = StarfieldCamera(self.focuser, scene)
        self.camera.PixelSizeX = self.camera.PixelSizeY = pixel_size
        self.server = FakeAlpacaServer(
            {"telescope": self.mount, "camera": self.camera, "focuser": self.focuser},
            host=host,
            port=port,
            discovery_port=discovery_port,
        )

    @property
    def address(self) -> str:
        return self.server.address

    @property
    def discovery_port(self) -> int | None:
        d = self.server.discovery
        return None if d is None else d.port

    def start(self) -> SkyDevice:
        self.server.start()
        return self

    def stop(self) -> None:
        self.server.stop()


def _terms(text: str) -> dict[str, float]:
    out = {}
    for part in filter(None, text.split(",")):
        name, _, value = part.partition("=")
        out[name.strip()] = float(value)
    return out


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--catalog", default="synthetic", help="catalog source of the sky's stars")
    ap.add_argument("--catalog-dir", help="the catalog's cache directory")
    ap.add_argument("--site", default="42.38,-71.13", help="LAT,LON (deg north, deg east)")
    ap.add_argument("--pointing-error", default="IH=150,ID=-40,NP=20", help="TPOINT terms, arcsec")
    ap.add_argument("--listen", default="127.0.0.1:0", help="HOST:PORT for Alpaca")
    ap.add_argument("--discovery-port", type=int, default=32227, help="UDP port (0: any)")
    args = ap.parse_args(argv)
    lat, lon = (float(v) for v in args.site.split(","))
    host, _, port = args.listen.rpartition(":")
    catalog: dict[str, Any] = {"source": args.catalog}
    if args.catalog_dir:
        catalog["cache_dir"] = args.catalog_dir
    device = SkyDevice(
        catalog=catalog,
        latitude=lat,
        longitude=lon,
        pointing_error=_terms(args.pointing_error),
        host=host,
        port=int(port),
        discovery_port=args.discovery_port,
    ).start()
    print(
        json.dumps(
            {"address": device.address, "discovery_port": device.discovery_port, "pid": os.getpid()}
        ),
        flush=True,
    )
    stop = threading.Event()
    for sig in (signal.SIGTERM, signal.SIGINT):
        signal.signal(sig, lambda *_: stop.set())
    stop.wait()
    device.stop()


if __name__ == "__main__":
    main()
